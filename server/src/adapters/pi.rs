//! Pi coding agent CLI: `pi --mode json`. Sessions are files in the Bot's own
//! session dir, addressed by a fixed --session-id, so resuming is the same call.

use super::{describe, output, str_of, Adapter, AgentEvent, ModelOption, RunInput};
use serde_json::Value;
use std::path::PathBuf;

/// OpenCode Go moved from `/zen/go/v1` to `/inference/go` and requires a stable
/// session header. Pi 0.73 does not send `x-opencode-session`, but it does send
/// `x-session-affinity` once `sendSessionAffinityHeaders` is on, which Go accepts.
/// This extension also adds current Go model ids that Pi's built-in list lacks.
const OPENCODE_GO_EXT: &str = r#"// Generated by SuperBot's Pi adapter. Do not edit.
const MODELS = [
  {
    id: "deepseek-v4.1-flash",
    name: "DeepSeek V4.1 Flash",
    api: "openai-completions",
    reasoning: true,
    thinkingLevelMap: { minimal: null, low: null, medium: null, high: "high", xhigh: "max" },
    input: ["text"],
    cost: { input: 0.14, output: 0.28, cacheRead: 0.0028, cacheWrite: 0 },
    contextWindow: 1000000,
    maxTokens: 384000,
    compat: {
      requiresReasoningContentOnAssistantMessages: true,
      thinkingFormat: "deepseek",
      sendSessionAffinityHeaders: true,
    },
  },
];
export default function (pi) {
  pi.registerProvider("opencode-go", {
    baseUrl: "https://opencode.ai/inference/go/openai/v1",
    apiKey: "OPENCODE_API_KEY",
    models: MODELS,
  });
}
"#;

/// Writes the extension once per machine and returns its path.
fn opencode_go_extension() -> Option<PathBuf> {
    let path = std::env::temp_dir().join("superbot-pi-opencode-go.js");
    if std::fs::read_to_string(&path).ok().as_deref() != Some(OPENCODE_GO_EXT) {
        std::fs::write(&path, OPENCODE_GO_EXT).ok()?;
    }
    Some(path)
}

#[derive(Default)]
pub struct Pi {
    /// Session we resumed, to avoid re-announcing it.
    resumed: Option<String>,
}

impl Adapter for Pi {
    fn bin(&self) -> &'static str {
        "pi"
    }

    fn args(&mut self, input: &RunInput, _out: &mut Vec<AgentEvent>) -> Vec<String> {
        self.resumed = input.session_id.clone();
        let mut a: Vec<String> = vec![
            "--mode".into(), "json".into(),
            "--session-dir".into(), input.state_dir.join("pi-sessions").display().to_string(),
        ];
        if let Some(ext) = opencode_go_extension() {
            a.extend(["--extension".into(), ext.display().to_string()]);
        }
        if let Some(id) = &input.session_id {
            a.extend(["--session".into(), id.clone()]);
        }
        // On Windows the CLI is a .cmd shim, so the command line goes through cmd.exe.
        // cmd.exe truncates at 8191 chars: pass the system prompt as a file instead.
        // pi reads a path given to --append-system-prompt as file contents.
        let mut used_file = false;
        if cfg!(windows) && std::fs::create_dir_all(&input.state_dir).is_ok() {
            let file = input.state_dir.join("pi-system-prompt.md");
            if std::fs::write(&file, &input.system).is_ok() {
                a.extend(["--append-system-prompt".into(), file.display().to_string()]);
                used_file = true;
            }
        }
        if !used_file {
            a.extend(["--append-system-prompt".into(), input.system.clone()]);
        }
        if let Some(m) = &input.model {
            a.extend(["--model".into(), m.clone()]);
        }
        if let Some(e) = &input.effort {
            a.extend(["--thinking".into(), e.clone()]);
        }
        if !self.prompt_stdin() {
            // A leading "@" would make pi read a file, so pad it.
            let p = &input.prompt;
            a.push(if p.starts_with('@') { format!(" {p}") } else { p.clone() });
        }
        a
    }

    fn prompt_stdin(&self) -> bool {
        cfg!(windows)
    }

    fn on_event(&mut self, e: &Value, out: &mut Vec<AgentEvent>) {
        match str_of(e, "type") {
            "session" => {
                // pi picks the session id itself; save it so the next run can resume.
                let id = str_of(e, "id");
                if !id.is_empty() && self.resumed.as_deref() != Some(id) {
                    self.resumed = Some(id.into());
                    out.push(AgentEvent::Session(id.into()));
                }
            }
            "message_update" => {
                let m = &e["assistantMessageEvent"];
                if str_of(m, "type") == "text_delta" {
                    out.push(AgentEvent::TextDelta(str_of(m, "delta").into()));
                }
            }
            "message_end" if str_of(&e["message"], "role") == "assistant" => {
                let msg = &e["message"];
                for c in msg["content"].as_array().into_iter().flatten() {
                    if str_of(c, "type") == "text" && !str_of(c, "text").trim().is_empty() {
                        out.push(AgentEvent::Text(str_of(c, "text").into()));
                    }
                }
                if str_of(msg, "stopReason") == "error" {
                    out.push(AgentEvent::Error(msg["errorMessage"].as_str().unwrap_or("Pi failed").into()));
                }
            }
            "tool_execution_start" => {
                out.push(AgentEvent::Tool { name: str_of(e, "toolName").into(), detail: describe(&e["args"]) })
            }
            _ => {}
        }
    }

    /// From `pi --list-models`: models with credentials set up. Columns:
    /// provider, model, context, max-out, thinking (yes/no), images.
    fn models(&self) -> Vec<ModelOption> {
        let efforts: Vec<String> = ["off", "minimal", "low", "medium", "high", "xhigh", "max"].map(String::from).into();
        let ext = opencode_go_extension();
        let mut args: Vec<String> = Vec::new();
        if let Some(ext) = &ext {
            args.extend(["--extension".into(), ext.display().to_string()]);
        }
        args.push("--list-models".into());
        let args: Vec<&str> = args.iter().map(String::as_str).collect();
        output("pi", &args)
            .lines()
            .skip(1)
            .filter_map(|l| {
                let c: Vec<&str> = l.split_whitespace().collect();
                let id = format!("{}/{}", c.first()?, c.get(1)?);
                let thinks = c.get(4) == Some(&"yes");
                Some(ModelOption { label: id.clone(), id, efforts: if thinks { efforts.clone() } else { vec![] }, aliases: vec![] })
            })
            .collect()
    }
}
